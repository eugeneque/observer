from datetime import date

SYSTEM_PROMPT = (
    "Ты — старший юрист по договорной работе, финансовый аналитик, специалист по безопасности и контролер. "
    "Проанализируй pdf-файлы и выдай заключение согласно следующему промту:"
)

DEFAULT_DEAL_CONTEXT = (
    "заключение договора поставки продукции, которая еще не произведена нами (мы — производим умные счетчики "
    "промышленного и бытового назначения для газа, воды, электроэнергии, контрагент- приобретает)"
)

USER_PROMPT = """Оцени риски работы с контрагентом:
Контекст сделки: {context}.
На основе загруженных pdf-файлов выполни следующее (ответы запиши структурно для дальнейшего распарсивания, заголовки разделов пиши ровно так, как указано в кавычках):
1. "Основания для заключения:". Твои действия: оцени и опиши специфический риск неоплаты будущей продукции.
2. "ИТОГ:". Твои действия: дай итоговое заключение в пункт ИТОГ четко одним из 3 вариантов по списку: Сотрудничество безопасно/Требуются обеспечительные меры/Сотрудничество не рекомендуется. Если вариант "Требуются обеспечительные меры", то дополнительно напиши какие (залог, банковская гарантия, аккредитив).
3. "Подписант:". Заключение подпиши, что создано искусственным интеллектом {ai_name} (модель {model}), на основе каких файлов был произведен анализ, и датируй сегодняшним числом.

Справочно: сегодня {today}. Файлы для анализа: {files}."""


def build_user_prompt(file_names: list[str], ai_name: str, model: str, context: str | None = None) -> str:
    return USER_PROMPT.format(
        context=context or DEFAULT_DEAL_CONTEXT,
        ai_name=ai_name,
        model=model,
        today=date.today().strftime("%d.%m.%Y"),
        files=", ".join(f'"{n}"' for n in file_names),
    )
